"""Generate docs/experimental_results.md from results/metrics (no hand-typed numbers)."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd

import config
from src import evaluator

M = config.METRICS_DIR


def md(df: pd.DataFrame) -> str:
    rows = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    rows += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def main():
    agg = pd.read_csv(M / "eval_summary.csv")
    meta = json.loads((M / "eval_meta.json").read_text())
    fm = json.loads((M / "forecast_metrics.json").read_text())
    pair = pd.read_csv(M / "paired_differences.csv")
    out = ["# Experimental results", "",
           "_Generated by `scripts/make_report.py` from `results/metrics/`. Do not edit by hand._", "",
           f"* Data source: **{meta['data_source']}**",
           f"* Test scenarios: **{meta['n_scenarios']}** identical simulated days (seeds {meta['seeds'][0]}-{meta['seeds'][-1]}), "
           f"{meta['mean_served_evs_per_scenario']:.1f} EVs served and {meta['mean_rejected_evs_per_scenario']:.1f} rejected (no free port) per day on average.",
           "* RL agents: " + "; ".join(f"{k}: {v['train_timesteps']:,} steps, {v['train_seconds']:.0f}s, training seed {v['seed']}" for k, v in meta["models"].items()), "",
           "## Policy comparison (mean ± std)", "", md(evaluator.pretty_table(agg)), "",
           "## Paired differences vs reference policies (same scenario; mean difference ± 95% CI)", ""]
    sel = pair[pair.policy.isin(["DQN", "PPO", "SAC"]) & pair.metric.isin(["total_cost", "peak_kw", "avg_unmet_kwh", "episode_reward"])].copy()
    sel["difference"] = [f"{m:.2f} ± {c:.2f}" for m, c in zip(sel.mean_diff, sel.ci95)]
    sel["relative_%"] = sel.rel_diff_pct.round(1)
    out += [md(sel[["policy", "reference", "metric", "difference", "relative_%"]]), "",
            "## Demand forecasting (held-out last 20% of the series)", "",
            md(pd.DataFrame(fm["metrics"]).T.round(3).reset_index().rename(columns={"index": "model"})), ""]
    qp = M / "eval_q_learning_simplified_summary.csv"
    if qp.exists():
        out += ["## Q-Learning on the simplified single-port environment", "",
                md(evaluator.pretty_table(pd.read_csv(qp), ["total_cost", "pct_fully_charged", "avg_unmet_kwh", "episode_reward"])), ""]
    (config.ROOT / "docs" / "experimental_results.md").write_text("\n".join(out))
    print("wrote docs/experimental_results.md")


if __name__ == "__main__":
    main()
